// The BOOKINGS section's slice of the API (console plan Part 11).
//
// Three different backends feed one sidebar group, and the difference matters
// when reading the types:
//
//   - Pooja bookings and the worklist come from /bookings/queue/… (Part 7).
//     Scoped: a temple_admin's queue is filtered in the query, not the client.
//   - Consults are astrologer bookings, /astrologers/… (Part 6). Owner-only,
//     and a different state machine — they never return to `confirmed`.
//   - Payments are the commerce ledger, /admin/payments (Part 8). Owner-only.
//
// Money is paise throughout, as stored. The settlement CSV is generated by the
// server for the same reason: an accountant reconciling a month must not be
// reconciling against a figure this app rounded.

import { authHeaders } from '../lib/session'
import { ApiError, apiGet, apiPatch, apiPost, apiUrl, qs } from './client'

// ---- pooja bookings ----

export interface BookingRow {
  id: number
  ref: string
  temple_id: string
  pooja_key: string
  pooja_name: string
  amount_paise: number
  service_fee_paise: number
  member_name: string
  member_nak: number | null
  when_label: string
  perform_on: string | null
  state: string
  operator_note: string
  created_at: string
  updated_at: string | null
}

export interface BookingDetail extends BookingRow {
  user_id: number
  user_name: string
  user_phone: string
  razorpay_order_id: string | null
  payment_status: string | null
  total_paise: number
}

export interface BookingPage {
  total: number
  limit: number
  offset: number
  items: BookingRow[]
}

export interface WorklistItem {
  id: number
  ref: string
  pooja_key: string
  pooja_name: string
  member_name: string
  member_nak: number | null
  when_label: string
  state: string
  operator_note: string
}

export interface Worklist {
  temple_id: string | null
  day: string | null
  total: number
  /** Bookings with no perform date — they are on no sheet at all. */
  undated: number
  groups: { nak: number | null; items: WorklistItem[] }[]
}

/** Query params the queue accepts. Undefined keys are dropped by `qs`. */
export interface QueueQuery {
  temple_id?: string
  state?: string
  pooja_key?: string
  ref?: string
  phone?: string
  booked_from?: string
  booked_to?: string
  perform_from?: string
  perform_to?: string
  limit?: number
  offset?: number
}

export const bookingQueue = (query: QueueQuery) =>
  apiGet<BookingPage>(`/bookings/queue${qs({ ...query })}`)

export const bookingDetail = (id: number) => apiGet<BookingDetail>(`/bookings/queue/${id}`)

export const bookingByRef = (ref: string) =>
  apiGet<BookingDetail>(`/bookings/queue/by-ref/${encodeURIComponent(ref)}`)

export const setBookingStatus = (id: number, status: string, note = '') =>
  apiPatch<BookingDetail>(`/bookings/queue/${id}/status`, { status, note })

export const setBookingNote = (id: number, note: string) =>
  apiPatch<BookingDetail>(`/bookings/queue/${id}/note`, { note })

/** Date a booking, or clear a wrong date. `null` is a real value here. */
export const setPerformOn = (id: number, performOn: string | null) =>
  apiPatch<BookingDetail>(`/bookings/queue/${id}/perform-on`, { perform_on: performOn })

export const worklist = (templeId?: string, day?: string) =>
  apiGet<Worklist>(`/bookings/queue/worklist${qs({ temple_id: templeId, day })}`)

export const bookingSettings = () =>
  apiGet<{ service_fee_paise: number }>('/bookings/settings')

/**
 * Download the settlement CSV for the current filter.
 *
 * Not an `<a href>`: the route is operator-gated and a navigation carries no
 * credential. The file is fetched with the header, then handed to the browser
 * as a click on a temporary object URL — revoked immediately, since nothing
 * refers to it once the download has started.
 */
export async function downloadBookingsCsv(query: QueueQuery): Promise<void> {
  const url = apiUrl(`/bookings/queue/export.csv${qs({ ...query })}`)
  const res = await fetch(url, { headers: authHeaders() })
  if (!res.ok) throw new ApiError(res.status, await res.text().catch(() => ''))
  const blob = URL.createObjectURL(await res.blob())
  const link = document.createElement('a')
  link.href = blob
  link.download = 'bookings.csv'
  link.click()
  URL.revokeObjectURL(blob)
}

