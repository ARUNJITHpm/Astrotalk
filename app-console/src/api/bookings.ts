export const listPayments = (query: PaymentQuery) =>
  apiGet<PaymentPage>(`/admin/payments${qs({ ...query })}`)

/**
 * Grant an entitlement by hand.
 *
 * `granted_by` is not a field: the server always records `"admin"`. The console
 * cannot claim a grant came from a purchase or a referral, because that is
 * exactly the audit trail the value exists to keep honest.
 */
export const grantEntitlement = (body: {
  user_id: number
  product_key: string
  reason?: string
  expires_at?: string | null
}) => apiPost<{ id: number; user_id: number; product_key: string }>('/admin/entitlements', body)
